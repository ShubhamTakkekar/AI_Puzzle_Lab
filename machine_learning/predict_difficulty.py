"""Inference module for predicting 8-puzzle difficulty from state features."""

from typing import Any, Dict, Tuple
import pandas as pd

from machine_learning.dataset_generator import extract_board_features
from machine_learning.train_model import FEATURE_NAMES, load_model_and_metrics
from puzzles.eight_puzzle import EightPuzzle


def predict_puzzle_difficulty(state: Tuple[int, ...]) -> Dict[str, Any]:
    """Predict the difficulty tier of an 8-puzzle board configuration.

    Args:
        state: 9-tuple representing the 3x3 board.

    Returns:
        Dictionary containing prediction result, class probabilities, features, and disclaimer.
    """
    is_valid, err = EightPuzzle.validate_state(state)
    if not is_valid:
        return {
            "valid": False,
            "error_message": err,
        }

    # Inversion parity check
    if not EightPuzzle.is_solvable(state):
        inversions = EightPuzzle.count_inversions(state)
        return {
            "valid": True,
            "solvable": False,
            "predicted_difficulty": "Unsolvable",
            "inversion_count": inversions,
            "error_message": (
                f"State has odd inversion parity ({inversions} inversions). "
                "Because legal sliding moves preserve parity, this configuration cannot reach the goal."
            ),
            "disclaimer": "Unsolvable states have infinite search depth and cannot be assigned a finite difficulty tier.",
        }

    # Load model artifacts
    clf, metrics = load_model_and_metrics()

    # Extract strictly mathematical features without target leakage
    features = extract_board_features(state)
    feature_df = pd.DataFrame([[features[k] for k in FEATURE_NAMES]], columns=FEATURE_NAMES)

    pred_class = clf.predict(feature_df)[0]
    probs = clf.predict_proba(feature_df)[0]
    classes = list(clf.classes_)

    prob_dict = {cls: round(float(prob), 4) for cls, prob in zip(classes, probs)}
    confidence = round(float(max(probs)) * 100, 1)

    return {
        "valid": True,
        "solvable": True,
        "predicted_difficulty": pred_class,
        "confidence_pct": confidence,
        "probabilities": prob_dict,
        "features": features,
        "model_accuracy": metrics.get("accuracy", 0.0),
        "disclaimer": (
            "Estimates are generated by a supervised Random Forest model trained on empirical state-space features. "
            "Predictions are probabilistic approximations, not mathematical guarantees."
        ),
    }
